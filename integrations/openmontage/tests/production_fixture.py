#!/usr/bin/env python3
"""Real four-second motion proof. Generated test patterns/tone, NOT an episode."""
import array
import hashlib
import importlib.util
import json
import math
from pathlib import Path
import subprocess
import sys
import wave

INTEGRATION = Path(__file__).resolve().parents[1]
PRODUCTION = INTEGRATION / 'scripts/production.py'
runtime = INTEGRATION / '.runtime/openmontage'


def command(*args, check=True):
    return subprocess.run([sys.executable, str(PRODUCTION), *args], check=check, capture_output=True, text=True)


def main():
    if Path(sys.prefix) != runtime / '.venv':
        subprocess.run([str(runtime / '.venv/bin/python'), str(Path(__file__).resolve()), *sys.argv[1:]], check=True)
        return
    slug = sys.argv[1] if len(sys.argv) > 1 else 'issue60-motion-fixture'
    if not slug.startswith('fixture-'):
        slug = 'fixture-' + slug
    spec = importlib.util.spec_from_file_location('fixture_data', Path(__file__).with_name('test_production.py'))
    fixture_data = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(fixture_data)
    data = fixture_data.example()
    command('init', slug, '--title', 'TECHNICAL FIXTURE — motion, cuts, captions; tone NOT speech')
    project = runtime / 'projects' / slug
    for name, hue in (('a', '0'), ('b', '90')):
        subprocess.run(['ffmpeg', '-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=s=640x360:r=30:d=2',
                        '-vf', f'hue=h={hue}', '-c:v', 'libx264', '-threads', '2', '-pix_fmt', 'yuv420p',
                        str(project / f'assets/{name}.mp4')], check=True)
    with wave.open(str(project / 'assets/tone.wav'), 'wb') as wav:
        wav.setparams((1, 2, 48000, 0, 'NONE', 'not compressed'))
        samples = array.array('h', (int(1800 * math.sin(2 * math.pi * 440 * i / 48000)) for i in range(4 * 48000)))
        if sys.byteorder != 'little':
            samples.byteswap()
        wav.writeframes(samples.tobytes())
    brief = data['brief']
    brief.update(version='1.0', title='TECHNICAL FIXTURE — NOT AN EPISODE', hook='Motion proof',
                 key_points=['Two generated moving sources', 'Tone is not narration'], tone='reverent', style='fixture-only')
    brief['metadata'].update(thematic_question='Does the verified pipeline preserve motion, cuts and timed captions?',
                            narration='fixture tone, NOT speech', end_tag_opt_out_reason='Fixture-only scope, not a production creative decision')
    scenes = data['scene_plan']
    scenes['version'] = '1.0'
    scenes['metadata'] = {'slots': [{'id': s['id'], 'queries': ['generated technical pattern', 'fixture moving shapes'],
        'hero': True, 'target_hold_seconds': 2, 'preferred_sources': ['fixture']} for s in scenes['scenes']]}
    for scene in scenes['scenes']:
        scene['description'] = 'Generated moving FFmpeg test pattern; fixture only'
    manifest = data['asset_manifest']
    manifest.update(version='1.0', total_cost_usd=0)
    manifest['metadata']['search_stats'] = {'path': 'fixture-generated-local', 'downloaded': 0}
    for asset in manifest['assets']:
        asset['source_tool'] = 'ffmpeg-lavfi-fixture' if asset['type'] == 'video' else 'stdlib-test-tone'
        checksum = hashlib.sha256((project / asset['path']).read_bytes()).hexdigest()
        manifest['metadata']['provenance'][asset['id']] = {'sha256': checksum,
            'rights_review': 'Generated by this test utility; no retrieved footage or speech', 'reviewed_by': 'fixture-harness-only'}
    narration = manifest['metadata']['narration']
    narration['audio_sha256'] = manifest['metadata']['provenance']['voice']['sha256']
    narration['segments'] = [{'words': [
        {'word': word, 'start': start, 'end': end} for word, start, end in (
            ('TECHNICAL', 0.1, 0.7), ('FIXTURE', 0.7, 1.5), ('TONE,', 2.1, 2.6), ('NOT', 2.6, 3.1), ('SPEECH', 3.1, 3.8))]}]
    data['edit_decisions']['version'] = '1.0'
    for cut in data['edit_decisions']['cuts']:
        cut['reason'] = 'Exercise a distinct generated motion source and exact two-second hold'
    sys.path.insert(0, str(runtime))
    from tools.video.video_compose import VideoCompose
    adapter_spec = importlib.util.spec_from_file_location('adapter', PRODUCTION)
    adapter = importlib.util.module_from_spec(adapter_spec)
    adapter_spec.loader.exec_module(adapter)
    # Check the actual pinned scene conversion, not a copy of its behavior.
    cuts = json.loads(json.dumps(data['edit_decisions']))
    for cut in cuts['cuts']:
        cut.pop('transition_in')
        cut.pop('transition_out')
    transport = adapter.transport_edit(cuts, {'a': project / 'assets/a.mp4', 'b': project / 'assets/b.mp4'},
                                       narration, project / 'assets/captions.srt', 4)
    for scene in VideoCompose._cuts_to_cinematic_scenes(transport['cuts']):
        assert scene['fadeInFrames'] == scene['fadeOutFrames'] == 0
    # All approvals below simulate gates ONLY for labeled test data. No owner approval is invented.
    for stage, name in [('idea', 'brief'), ('scene_plan', 'scene_plan'), ('assets', 'asset_manifest'), ('edit', 'edit_decisions')]:
        (project / 'artifacts' / f'{name}.json').write_text(json.dumps(data[name], indent=2))
        premature = command('checkpoint', slug, stage, '--approve', 'fixture attempt before pending', check=False)
        assert premature.returncode != 0, 'Gate allowed approval without a pending artifact'
        command('checkpoint', slug, stage)
        command('checkpoint', slug, stage, '--approve', 'FIXTURE-ONLY simulated approval; not owner production consent')
    rejected = command('render', slug, check=False)
    assert rejected.returncode != 0 and 'fixture' in rejected.stderr.lower(), rejected.stdout + rejected.stderr
    result = command('render', slug, '--fixture')
    print(result.stdout)
    report = json.loads((project / 'artifacts/render_report.json').read_text())
    assert report['metadata']['fixture'] is True
    assert report['metadata']['caption_words'] == 5
    checkpoint = json.loads((project / 'checkpoint_compose.json').read_text())
    assert checkpoint['status'] == report['metadata']['checkpoint_status']
    if report['metadata']['review_status'] != 'pass':
        assert checkpoint['status'] == 'awaiting_human', 'Revision must not be completed'
    assert (project / 'assets/captions.srt').read_text().count('-->') > 0
    assert (project / 'checkpoint_compose.json').is_file()
    print(f'FIXTURE VERIFIED: {project}; generated motion + test tone + captions, not a delivered episode')


if __name__ == '__main__':
    try:
        main()
    except subprocess.CalledProcessError as exc:
        print(exc.stdout or '', exc.stderr or '', file=sys.stderr)
        raise SystemExit(exc.returncode)
